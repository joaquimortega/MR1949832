#!/usr/bin/env python3
"""Generate the self-contained `Challenge.lean` and `comparator/config.json`.

Challenge.lean = OrtegaCerdaMultipliers/Defs.lean (verbatim, imports only Mathlib)
               + the main-theorem statements in comparator/statements.lean (with `sorry`).

Every theorem in comparator/statements.lean must exist with the *same name and statement* in the
project (namespace `OC`); Solution.lean just imports the project.
Run from the repository root:  python3 scripts/make_challenge.py
"""
import json, re, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
defs = (root / "OrtegaCerdaMultipliers" / "Defs.lean").read_text()
stmts = (root / "comparator" / "statements.lean").read_text()

end = defs.rfind("end OC")
assert end != -1, "Defs.lean must end with `end OC`"
header = ("-- AUTO-GENERATED by scripts/make_challenge.py from OrtegaCerdaMultipliers/Defs.lean and\n"
          "-- comparator/statements.lean.  Do not edit by hand.\n")
challenge = header + defs[:end] + "\n/-! ## Main results -/\n\n" + stmts.strip() + "\n\nend OC\n"
(root / "Challenge.lean").write_text(challenge)

names = ["OC." + n for n in re.findall(r"^theorem\s+(\S+)", stmts, flags=re.M)]
config = {
    "challenge_module": "Challenge",
    "solution_module": "Solution",
    "theorem_names": names,
    "permitted_axioms": ["propext", "Quot.sound", "Classical.choice"],
}
(root / "comparator" / "config.json").write_text(json.dumps(config, indent=2) + "\n")
print("wrote Challenge.lean and comparator/config.json with", len(names), "theorems:", names)
