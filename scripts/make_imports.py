#!/usr/bin/env python3
"""Generate `blueprint/IMPORTS.md`: module → Lean files → imports, declaration and `sorry`
counts, and the module dependency graph (transitive reduction of the file imports).
Run from the repository root:  python3 scripts/make_imports.py
"""
import pathlib, re

root = pathlib.Path(__file__).resolve().parent.parent
pkg = root / "OrtegaCerdaMultipliers"

MODULES = [  # (module, title, file prefixes relative to OrtegaCerdaMultipliers/)
    ("M00", "Definitions", ["Defs"]),
    ("M01", "Foundations", ["Foundations/"]),
    ("M02", "Potentials", ["Potential/"]),
    ("M03", "Doubling", ["Doubling/"]),
    ("M04", "Regularization (Lemma 6)", ["Regularization"]),
    ("M05", "Partition (Lemma 4)", ["Partition/"]),
    ("M06", "Quadrature (Lemma 5)", ["Quadrature"]),
    ("M07", "LogModulus", ["LogModulus", "LogModulusWeak"]),
    ("M08", "Multiplier (Theorem 4)", ["Multiplier/"]),
    ("M09", "SeveralMultipliers (Prop. 2)", ["SeveralMultipliers"]),
    ("M10", "ModelKernels (Lemmas 7, 8)", ["ModelKernels"]),
    ("M11", "Theorem 2", ["Theorem2"]),
    ("M12", "Theorem 1, Prop. 1", ["Theorem1"]),
    ("M13", "Theorem 5", ["Line/", "Theorem5"]),
    ("M14", "Theorem 3", ["Theorem3", "TheoremOCSProof"]),
    ("Main", "re-export", ["Main"]),
]

def rel(p):
    return str(p.relative_to(pkg))[:-5]

def module_of(r):
    for m, _, prefs in MODULES:
        for pr in prefs:
            if (pr.endswith("/") and r.startswith(pr)) or r == pr:
                return m
    raise KeyError(r)

def strip_comments(s):
    out, i, depth = [], 0, 0
    while i < len(s):
        if s.startswith("/-", i):
            depth += 1; i += 2; continue
        if depth and s.startswith("-/", i):
            depth -= 1; i += 2; continue
        if not depth and s.startswith("--", i):
            j = s.find("\n", i); i = len(s) if j < 0 else j; continue
        if not depth:
            out.append(s[i])
        i += 1
    return "".join(out)

DECL = re.compile(r"^(?:noncomputable )?(?:theorem|lemma|def|structure|class|instance|abbrev)\b", re.M)

files = sorted(pkg.rglob("*.lean"))
info = {}
for p in files:
    r = rel(p)
    txt = p.read_text()
    code = strip_comments(txt)
    imps = [l.split()[1] for l in txt.splitlines() if l.startswith("import ")]
    proj = [i.removeprefix("OrtegaCerdaMultipliers.").replace(".", "/") for i in imps
            if i.startswith("OrtegaCerdaMultipliers.")]
    other = [i for i in imps if not i.startswith("OrtegaCerdaMultipliers.")]
    info[r] = dict(mod=module_of(r), imports=proj, other=other,
                   decls=len(DECL.findall(code)), sorries=len(re.findall(r"\bsorry\b", code)))

# module graph
edges = {m: set() for m, _, _ in MODULES}
for r, d in info.items():
    for i in d["imports"]:
        mi = module_of(i)
        if mi != d["mod"]:
            edges[d["mod"]].add(mi)

def reach(m, seen=None):
    seen = set() if seen is None else seen
    for n in edges[m]:
        if n not in seen:
            seen.add(n); reach(n, seen)
    return seen

reduced = {m: {n for n in es if not any(n in reach(k) for k in es if k != n)} for m, es in edges.items()}

lines = ["# Lean files and imports (generated)", "",
         "Generated by `python3 scripts/make_imports.py` from the `import` lines of",
         "`OrtegaCerdaMultipliers/**/*.lean`. Counts: `decls` counts the theorems, definitions, structures and",
         "instances; `sorry` counts the `sorry` tokens outside comments.", "",
         "## Files", "",
         "| module | file | decls | sorry | project imports |", "|---|---|---:|---:|---|"]
for m, title, _ in MODULES:
    for r in sorted(k for k, d in info.items() if d["mod"] == m):
        d = info[r]
        imps = ", ".join(f"`{i}`" for i in d["imports"]) or ("Mathlib" if d["other"] else "—")
        lines.append(f"| {m} | `{r}.lean` | {d['decls']} | {d['sorries']} | {imps} |")
lines += ["", "## Modules", "", "| module | content | files | decls | sorry | direct module dependencies |",
          "|---|---|---:|---:|---:|---|"]
for m, title, _ in MODULES:
    fs = [d for d in info.values() if d["mod"] == m]
    deps = ", ".join(sorted(reduced[m])) or "Mathlib"
    lines.append(f"| {m} | {title} | {len(fs)} | {sum(d['decls'] for d in fs)} | "
                 f"{sum(d['sorries'] for d in fs)} | {deps} |")
tot_d = sum(d["decls"] for d in info.values()); tot_s = sum(d["sorries"] for d in info.values())
lines += ["", f"Total: {len(info)} files, {tot_d} declarations, {tot_s} `sorry`.", "",
          "## Dependency graph (transitive reduction)", "", "```"]
for m, _, _ in MODULES:
    lines.append(f"{m:5} ← {', '.join(sorted(reduced[m])) or 'Mathlib'}")
lines += ["```", "", "Full (transitive) dependencies:", "", "```"]
for m, _, _ in MODULES:
    lines.append(f"{m:5} ← {', '.join(sorted(reach(m)))}")
lines += ["```", ""]
(root / "blueprint" / "IMPORTS.md").write_text("\n".join(lines))
print("\n".join(lines[-40:]))
